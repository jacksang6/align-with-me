# Per-version verify script generator: version parity + baseline + click-through skeleton.
"""gen_verify_script.py - scaffold the deployment regression script for one
prototype version (criteria pool 8/16/18). The generated script is committed
with the version tag; it refuses to pass until its click-through steps are
filled, so an empty gate is never a fake gate.

Interface:
    python gen_verify_script.py --version <tag> --url <deployed-url>
                                [--prev-snapshot <file>] [--out <path>]

The generated verify_<version>.py (default out: verify_<version>.py):
    1. version parity  the deployed dock must carry the version tag.
    2. baseline        with --prev-snapshot: the confirmed markup survives
                       verbatim on the deployed page (append-only).
    3. click-through   a marked skeleton for the per-version behaviour
                       steps (criteria pool 16); the TODO marker makes the
                       script exit 2 until the steps are filled.

Exit codes: 0 = generated ([OK] on stdout); 2 = argument or validation
error (one "[ERR] verify script generation failed" line, then
{"error": {"errors": [{loc, type, msg, fix}]}} on stderr).

Stdlib only. Every path comes from the command line.
"""

import argparse
import json
import re
import sys
from pathlib import Path
from string import Template
from urllib.parse import urlparse

TEMPLATE = Template('''# verify_$version.py - generated by gen_verify_script.py; commit with tag $version.
# Deployment regression for prototype version $version (criteria pool 8/16/18).
# Usage: python $name [--url <deployed-url>]
import argparse
import json
import re
import sys
from urllib.request import urlopen

VERSION = '$version'
DEFAULT_URL = '$url'
PREV_SNAPSHOT = $prev  # previous round's snapshot html (or None)
CLICKTHROUGH_FILLED = False  # set True when the steps below are filled


def fail(issues):
    sys.stderr.write('[ERR] verify $version failed\\n')
    sys.stderr.write(json.dumps({'error': {'errors': issues}}) + '\\n')
    return 2


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--url', default=DEFAULT_URL)
    args = ap.parse_args()
    issues = []
    try:
        page = urlopen(args.url, timeout=15).read().decode('utf-8', 'replace')
    except OSError as exc:
        return fail([{'loc': '--url', 'type': 'url', 'msg': str(exc),
                      'fix': 'check the deployed page is reachable'}])
    match = re.search(r'<div[^>]*class="[^"]*dock[^"]*"[^>]*>(.*?)</div>',
                      page, re.S)
    dock = match.group(1) if match else ''
    if VERSION not in dock:
        issues.append({'loc': 'dock', 'type': 'version',
                       'msg': 'the dock does not carry version $version',
                       'fix': 'deploy the build of the tagged prototype '
                              'version'})
    if PREV_SNAPSHOT:
        try:
            with open(PREV_SNAPSHOT, encoding='utf-8') as handle:
                base = handle.read()
        except OSError as exc:
            issues.append({'loc': 'baseline', 'type': 'baseline',
                           'msg': str(exc),
                           'fix': 'pass the previous snapshot path'})
        else:
            if ' '.join(base.split()) not in ' '.join(page.split()):
                issues.append({'loc': 'baseline', 'type': 'baseline',
                               'msg': 'confirmed markup changed on the '
                                      'deployed page',
                               'fix': 'restore the confirmed markup '
                                      'verbatim'})
    # click-through (criteria pool 16): drive every button and observe the
    # real state change it promises. Fill the steps for this version, then
    # set CLICKTHROUGH_FILLED = True above.
    # click-through steps for $version (playwright)
    if not CLICKTHROUGH_FILLED:
        issues.append({'loc': 'clickthrough', 'type': 'clickthrough',
                       'msg': 'the click-through steps are not filled '
                              'for $version',
                       'fix': 'fill the click-through steps below and '
                              'set CLICKTHROUGH_FILLED = True'})
    if issues:
        return fail(issues)
    print('[OK] verify $version passed')
    return 0


if __name__ == '__main__':
    sys.exit(main())
''')


def _setup_streams():
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding='utf-8', errors='replace')
        except (AttributeError, ValueError):
            pass


class _Parser(argparse.ArgumentParser):
    def error(self, message):
        _emit([{'loc': 'argv', 'type': 'args', 'msg': message,
                'fix': 'run with --help to see the accepted flags'}])
        raise SystemExit(2)


def _emit(errors):
    sys.stderr.write('[ERR] verify script generation failed\n')
    sys.stderr.write(json.dumps({'error': {'errors': errors}},
                                ensure_ascii=False) + '\n')
    return 2


def main(argv=None):
    _setup_streams()
    parser = _Parser()
    parser.add_argument('--version', required=True)
    parser.add_argument('--url', required=True)
    parser.add_argument('--prev-snapshot', default='')
    parser.add_argument('--out', default='')
    args = parser.parse_args(argv)
    errors = []
    if not re.fullmatch(r'v[0-9][\w.]*', args.version):
        errors.append({'loc': '--version', 'type': 'version',
                       'msg': 'version must look like v0.80 (got %r)'
                              % args.version,
                       'fix': 'pass the ladder version tag'})
    parsed = urlparse(args.url)
    if parsed.scheme not in ('http', 'https') or not parsed.netloc:
        errors.append({'loc': '--url', 'type': 'url',
                       'msg': 'the deployed page url must be http(s)',
                       'fix': 'pass the deployed environment url'})
    prev = ''
    if args.prev_snapshot:
        prev_path = Path(args.prev_snapshot)
        if not prev_path.is_file():
            errors.append({'loc': '--prev-snapshot', 'type': 'snapshot',
                           'msg': 'previous snapshot not found: %s'
                                  % args.prev_snapshot,
                           'fix': "pass the previous round's snapshot file"})
        else:
            prev = str(prev_path)
    out = (Path(args.out) if args.out
           else Path('verify_%s.py' % args.version))
    if not errors:
        try:
            out.write_text(TEMPLATE.substitute(
                version=args.version, url=args.url, prev=prev or 'None',
                name=out.name), encoding='utf-8', newline='\n')
        except OSError as exc:
            errors.append({'loc': '--out', 'type': 'io',
                           'msg': 'cannot write the verify script: %s' % exc,
                           'fix': 'pass a writable --out path'})
    if errors:
        return _emit(errors)
    sys.stdout.write('[OK] verify script written: %s\n' % out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
